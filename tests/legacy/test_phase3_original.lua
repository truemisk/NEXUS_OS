local function key(scan,char) return {'key_down','keyboard-01',char or 0,scan or 0} end
local function boot(w,h,seq,extra)
  local gpu=GPU.new(w,h,{maxW=math.max(w,80),maxH=math.max(h,25)})
  local deps={term=Mock.term(gpu),component=Mock.new({gpu}),computer=Mock.computer(),fs=fs,
    persistence={read=function() return '' end,write=function() return true end}}
  deps.event=Mock.events(seq,gpu)
  deps.runShell=extra
  deps.keys={up=200,down=208,left=203,right=205,enter=28,numpadenter=156,esc=1,tab=15}
  local ok,res=Run(deps)
  assert(ok,tostring(res));assert(deps.term.blink==true)
  assert(not gpu.snapshot():find('%S'))
  return table.concat(deps.event.snaps,'\n'),res
end
