package.path='./src/?.lua;./tests/?.lua;'..package.path
local GPU=require('mock_gpu')
local Mock=require('mock_components')
local Config=require('nexus.core.config')
local Theme=require('nexus.core.theme')
local Notices=require('nexus.core.notices')
local Display=require('nexus.core.display')
local Widgets=require('nexus.ui.widgets')
local Hardware=require('nexus.core.hardware')
local Input=require('nexus.core.input')
local Run=require('nexus.main')
local passed,failed=0,0
local function test(label,fn)
  local ok,err=pcall(fn)
  if ok then passed=passed+1;print('PASS '..label)
  else failed=failed+1;print('FAIL '..label..': '..tostring(err)) end
end
local function makePersistence(raw,fail)
  local store={raw=raw,writes=0}
  return {read=function() return store.raw end,write=function(data)
    store.writes=store.writes+1
    if fail then return false,'readonly' end
    store.raw=data;return true
  end},store
end
local function key(code,char) return {'key_down','keyboard-01',char or 0,code} end
local function make(w,h,seq,persistence,options)
  local gpu=GPU.new(w,h,options)
  local deps={term=Mock.term(gpu),component=Mock.new({gpu}),computer=Mock.computer(),persistence=persistence}
  deps.event=Mock.events(seq,gpu)
  deps.keys={up=200,down=208,left=203,right=205,enter=28,numpadenter=156,esc=1,
    tab=15,f1=59,f2=60,f3=61,f4=62,f5=63,f6=64}
  return deps,gpu
end
local function completed(w,h,seq,raw,options)
  local store,back=makePersistence(raw)
  local deps,gpu=make(w,h,seq,store,options)
  local ok,res=Run(deps)
  assert(ok,tostring(res))
  assert(not gpu.snapshot():find('%S'),'original GPU screen not cleared')
  assert(deps.term.blink==true)
  return deps,gpu,back,res
end
local function has(deps,word)
  local text=table.concat(deps.event.snaps,'\n')
  assert(text:find(word,1,true),'Missing UI: '..word)
end

test('theme cycle cyan-green-amber-cyan',function()
  assert(Theme.next('cyan')=='green')
  assert(Theme.next('green')=='amber')
  assert(Theme.next('amber')=='cyan')
  assert(Theme.select(8,'amber').accent~=Theme.select(8,'cyan').accent)
end)
test('monochrome fallback is readable',function()
  for _,name in ipairs(Theme.names) do
    local t=Theme.select(1,name)
    assert(t.bg==0 and t.text==0xffffff and t.activeBg==0xffffff)
  end
end)
test('config defaults, whitespace, bad keys, no code execution',function()
  local c=Config.parse('theme=amber\nlayout=compact\nsplash=true\nnotifications=false\nblah=1\ntheme=os.execute\n')
  assert(c.theme=='amber' and c.layout=='compact' and c.splash and c.notifications==false)
  assert(Config.parse('theme=unknown').theme=='cyan')
  assert(Config.parse(string.rep('x',5000)).layout=='auto')
end)
test('config deterministic round trip',function()
  local store,back=makePersistence(nil)
  local c=Config.new(store)
  assert(c:set('theme','green'))
  assert(c:set('layout','standard'))
  assert(c:save())
  assert(back.writes==1)
  local second=Config.new(store)
  assert(second.data.theme=='green' and second.data.layout=='standard')
end)
test('config refuses unsupported setting values',function()
  local c=Config.new(makePersistence(nil))
  assert(not c:set('theme','bad'))
  assert(not c:set('not_real','1'))
  assert(c.data.theme=='cyan')
end)
test('read-only config gives failure, UI still works',function()
  local store=makePersistence(nil,true)
  local c=Config.new(store)
  assert(c:set('theme','amber'))
  local ok,why=c:save()
  assert(not ok and why=='readonly')
end)
test('toast queue is bounded to 8 messages',function()
  local n=Notices.new()
  for i=1,25 do n:push('message '..i,'info',i) end
  assert(#n.history==8 and n.history[1].message=='message 25')
  assert(n:tick(29));assert(not n.current)
end)
test('safe resolution presets are within hardware limits',function()
  local d=Display.new(GPU.new(80,25),function() return 0 end)
  local p=d:presets(80,25,80,25)
  assert(#p==2 and p[2].w==50 and p[2].h==16)
  local tiny=d:presets(18,7,18,7)
  assert(#tiny==1)
end)
test('safe resolution preview confirms',function()
  local gpu=GPU.new(80,25)
  local sec=1
  local d=Display.new(gpu,function() return sec end)
  assert(d:preview(50,16))
  assert(gpu.getResolution()==50)
  sec=2;assert(not d:tick())
  assert(d:confirm() and not d.pending)
  assert(gpu.getResolution()==50)
end)
test('safe resolution preview reverts on timeout',function()
  local gpu=GPU.new(80,25)
  local sec=1
  local d=Display.new(gpu,function() return sec end)
  assert(d:preview(50,16))
  sec=14;assert(d:tick())
  local w,h=gpu.getResolution()
  assert(w==80 and h==25 and not d.pending)
end)
test('safe resolution preview reverts on ESC',function()
  local gpu=GPU.new(80,25)
  local d=Display.new(gpu,function() return 0 end)
  assert(d:preview(50,16))
  assert(d:rollback())
  assert(gpu.getResolution()==80)
end)
test('safe resolution preview refuses unsupported target',function()
  local gpu=GPU.new(80,25)
  local d=Display.new(gpu,function() return 0 end)
  assert(not d:preview(100,80))
  assert(gpu.getResolution()==80)
  assert(not d.pending)
end)
test('responsive compact/standard modes',function()
  assert(Widgets.mode(32,12)=='compact')
  assert(Widgets.mode(80,25)=='standard')
  assert(Widgets.mode(80,25,'compact')=='compact')
  assert(Widgets.mode(50,16,'standard')=='compact')
end)
test('key shortcuts and ignored foreign screen input',function()
  local deps=make(80,25,{key(1)},makePersistence(nil))
  local hw=assert(Hardware.new(deps.component,deps.computer,deps.term))
  for scan,name in pairs({[59]='home',[60]='settings',[61]='system',[62]='theme',[63]='refresh',[64]='notifications',[15]='tab'}) do
    assert(Input.decode('key_down','keyboard-01',0,scan,hw,deps.keys).kind==name)
  end
  assert(not Input.decode('touch','unrelated-screen',4,5,hw,deps.keys))
end)
test('F2 Settings + theme change persist + F4 global theme shortcut',function()
  local deps,gpu,store=completed(80,25,{key(60),key(28),key(62),key(59),key(1)},nil)
  has(deps,'CONTROL CENTER');has(deps,'Color theme')
  assert(store.raw:find('theme=amber',1,true))
end)
test('settings persisted between launches',function()
  local persistence,store=makePersistence('theme=green\nlayout=compact\n')
  local deps,gpu=make(80,25,{key(60),key(1),key(1)},persistence)
  local ok,res=Run(deps)
  assert(ok,tostring(res))
  assert(res.theme=='green' and res.mode=='compact')
  assert(store.writes==0)
end)
test('F3 System and F6 Notifications launch + return',function()
