-- Regression: the terminal proxy can expose getScreen while method lookups
-- for rendering are missing, even though component.invoke still works.
test("proxy methods missing, component.invoke fallback renders desktop",function()
  local real=GPU.new(80,25,{address="56d3a4e9",screen="6f1fa8eb"})
  local proxy={address=real.address,getScreen=real.getScreen}
  local cp=Mock.new({real},{screens={"6f1fa8eb"}})
  local originalProxy=cp.proxy
  cp.proxy=function(address)
    if address==real.address then return proxy end
    return originalProxy(address)
  end
  local invokeCount=0
  cp.invoke=function(address,name,...)
    assert(address==real.address,"unexpected invoke address")
    invokeCount=invokeCount+1
    return real[name](...)
  end
  local term=Mock.term(real)
  term.gpu=function() return proxy end
  local hw=assert(Hardware.new(cp,Mock.computer(),term))
  assert(hw.gpu.address==real.address)
  assert(({hw.gpu.getResolution()})[1]==80)
  hw.gpu.set(1,1,"OK")
  assert(real.snapshot():find("OK",1,true))
  assert(invokeCount>=2)
end)
test("invocation-only terminal GPU can run full NEXUS shell",function()
  local real=GPU.new(80,25,{address="invocation-gpu",screen="invocation-screen"})
  local proxy={address=real.address,getScreen=real.getScreen}
  local cp=Mock.new({real},{screens={"invocation-screen"}})
  cp.invoke=function(addr,name,...)
    assert(addr==real.address)
    return real[name](...)
  end
  local term=Mock.term(real)
  term.gpu=function() return proxy end
  local deps={term=term,component=cp,computer=Mock.computer()}
  deps.event=Mock.events({{"key_down","keyboard-01",0,1}},real)
  deps.keys={up=200,down=208,left=203,right=205,enter=28,numpadenter=156,esc=1}
  local ok, report=Run(deps)
  assert(ok,tostring(report))
  assert(report.mode=="standard")
  assert(real.calls.set>0)
  assertEmpty(real)
end)
test("proxy getResolution error, invoke fallback recovers",function()
  local real=GPU.new(80,25,{address="real",screen="live-screen"})
  local proxy={address=real.address,getScreen=real.getScreen,
    getResolution=function() error("proxy read failure") end}
  local cp=Mock.new({real},{screens={"live-screen"}})
  cp.invoke=function(addr,name,...)
    assert(addr=="real")
    return real[name](...)
  end
  local term=Mock.term(real)
  term.gpu=function() return proxy end
  local hw=assert(Hardware.new(cp,Mock.computer(),term))
  assert(hw:resolution()==80)
end)
