test("input key arrows + ENTER ESC",function()
  local deps=setup(32,12)
  local hw=assert(Hardware.new(deps.component,deps.computer,deps.term))
  for code,kind in pairs({[200]="up",[208]="down",[203]="left",[205]="right",[28]="enter",[1]="back"}) do
    assert(Input.decode("key_down","keyboard-01",0,code,hw,deps.keys).kind==kind)
  end
  assert(not Input.decode("key_down","other-keyboard",0,28,hw,deps.keys))
  assert(not Input.decode("nonsense",nil,nil,nil,hw,deps.keys))
end)
test("input filters touch and resize by screen",function()
  local deps=setup(32,12)
  local hw=assert(Hardware.new(deps.component,deps.computer,deps.term))
  assert(not Input.decode("touch","other-screen",2,3,hw))
