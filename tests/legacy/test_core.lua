local passed,failed=0,0
local function test(name,func)
  local ok,err=pcall(func)
  if ok then passed=passed+1; print("PASS "..name)
  else failed=failed+1; print("FAIL "..name..": "..tostring(err)) end
end
local function setup(w,h,events,opts)
  opts=opts or {}
  local gpu=GPU.new(w,h,opts)
  local deps={term=Mock.term(gpu), component=Mock.new({gpu},{extra={"filesystem","transposer"}}),computer=Mock.computer()}
  deps.event=Mock.events(events or {},gpu)
  deps.keys={up=200,down=208,left=203,right=205,enter=28,numpadenter=156,esc=1}
  return deps,gpu
end
local function key(code,kb)
  return {"key_down",kb or "keyboard-01",0,code}
end
local function contains(haystack,needle)
  assert(haystack:find(needle,1,true),"Missing text: "..needle)
end
local function assertEmpty(gpu)
  assert(not gpu.snapshot():find("%S"),"Exit did not clear the screen")
end

